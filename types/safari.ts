// types/safari.ts
// アプリ全体で共有する「ゲーム経済圏」の型定義。
// Zustand ストア・各コンポーネントから import して使う。

// ─────────────────────────────────────────────────────────────────────────────
// 動物（裏庭・物流キュー 共通）
// ─────────────────────────────────────────────────────────────────────────────
export type AnimalRarity = "ふつう" | "レア" | "でんせつ";

export interface GameAnimal {
  /** ユニーク ID（nanoid 等で生成） */
  id: string;
  name: string;
  emoji: string;
  rarity: AnimalRarity;
  /** 同種を一括管理する場合の匹数（デフォルト 1） */
  count: number;
}

// ─────────────────────────────────────────────────────────────────────────────
// インベントリアイテム（クラフト素材・農作物など）
// ─────────────────────────────────────────────────────────────────────────────
export type InventoryMap = Record<string, number>;

// ─────────────────────────────────────────────────────────────────────────────
// 勲章
// ─────────────────────────────────────────────────────────────────────────────
export interface Medal {
  id: string;
  emoji: string;
  name: string;
  /** 解除日（ja-JP ロケール文字列）。null = まだ未取得 */
  unlockedAt: string | null;
}

// ─────────────────────────────────────────────────────────────────────────────
// トラック発送の報酬結果
// ─────────────────────────────────────────────────────────────────────────────
export interface ShipResult {
  earnedCoins: number;
  newMedals: Medal[];
}
